#!/usr/bin/env python3
"""Writes crates/radeon/src/names.rs from xf86-video-ati's radeon_reg.h."""
import collections
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
header = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "references/src/xf86-video-ati/src/radeon_reg.h"
mmio, pll = {}, {}
for line in header.read_text().splitlines():
    m = re.match(r"#\s*define\s+((?:RADEON|R200|R300)_\w+)\s+0x([0-9a-fA-F]{3,4})\b(.*)", line)
    if not m:
        continue
    name, value, rest = m.group(1), int(m.group(2), 16), m.group(3)
    table = pll if "PLL" in rest and "/*" in rest else mmio
    if table is mmio and (value % 4 or (len(m.group(2)) == 3 and not line.startswith("#define"))):
        continue
    table.setdefault(value, name)

# Offsets that radeon_reg.h names twice, where the first name is not the R300 one.
mmio.update({0x0060: "RADEON_GPIO_VGA_DDC", 0x0150: "RADEON_MC_STATUS"})

out = ["// Generated by scripts/radeon-names.py from radeon_reg.h in xf86-video-ati",
       "// (Copyright 2000 ATI Technologies Inc. and VA Linux Systems Inc.; Kevin E. Martin,",
       "// Rickard E. Faith, Alan Hourihane), which is under the MIT license.", ""]
for title, table in (("MMIO", mmio), ("PLL", pll)):
    out.append(f"const {title}: &[(u32, &str)] = &[")
    out += [f"    ({k:#06x}, \"{v}\")," for k, v in sorted(table.items())]
    out.append("];")
    out.append("")
out += [
    "fn lookup(table: &[(u32, &'static str)], key: u32) -> &'static str {",
    "    table.binary_search_by_key(&key, |e| e.0).map_or(\"?\", |i| table[i].1)",
    "}",
    "",
    "pub(crate) fn mmio_name(reg: u32) -> &'static str {",
    "    lookup(MMIO, reg)",
    "}",
    "",
    "pub(crate) fn pll_name(index: u32) -> &'static str {",
    "    lookup(PLL, index)",
    "}",
    "",
]
(root / "crates/radeon/src/names.rs").write_text("\n".join(out))
